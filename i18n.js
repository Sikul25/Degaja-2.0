  function getLang() {
    const saved = localStorage.getItem(LANG_KEY);
    return SUPPORTED.includes(saved) ? saved : "de";
  }

  function setLang(lang) {
    if (!SUPPORTED.includes(lang)) return;
    localStorage.setItem(LANG_KEY, lang);
    location.reload();
  }

  function t(key) {
    const lang = getLang();
    return (T[lang] && T[lang][key]) ?? (T.de[key] ?? key);
  }

  window.degajaI18n = { getLang, setLang, t, SUPPORTED };

  const FLAGS = { de: "🇩🇪", en: "🇬🇧", fr: "🇫🇷", es: "🇪🇸" };

  function buildSwitcher() {
    const wrap = document.createElement("div");
    wrap.className = "lang-switch";
    wrap.setAttribute("aria-label", "Sprache wählen / Language");
    const current = getLang();
    SUPPORTED.forEach(lang => {
      const btn = document.createElement("button");
      btn.type = "button";
      btn.className = "lang-flag" + (lang === current ? " active" : "");
      btn.textContent = FLAGS[lang];
      btn.setAttribute("aria-label", lang);
      btn.addEventListener("click", () => setLang(lang));
      wrap.appendChild(btn);
    });
    return wrap;
  }

  function applyTranslations() {
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      const val = t(key);
      if (val !== undefined) el.textContent = val;
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
      const key = el.getAttribute("data-i18n-placeholder");
      const val = t(key);
      if (val !== undefined) el.setAttribute("placeholder", val);
    });
    document.documentElement.lang = getLang();
    const metaTitle = t("meta.title");
    if (metaTitle && !metaTitle.startsWith("meta.")) document.title = metaTitle;
    const metaDesc = document.querySelector('meta[name="description"]');
    const descVal = t("meta.description");
    if (metaDesc && descVal && !descVal.startsWith("meta.")) metaDesc.setAttribute("content", descVal);
  }

  function init() {
    const header = document.querySelector(".site-header");
    if (header && !header.querySelector(".lang-switch")) {
      header.insertBefore(buildSwitcher(), header.querySelector(".login-btn"));
    }
    applyTranslations();
  }

  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", init, { once: true });
  else init();
